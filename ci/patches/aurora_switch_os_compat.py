#!/usr/bin/env python3
"""Patch HayatoG/aurora-switch so dusk-cn's Switch build sees the two APIs that
desktop aurora grew after the fork point.

aurora-switch (branch `dusklight-switch-port`, last commit 2026-07-02) is based on
an older aurora than extern/aurora (3227d76). Dusk code targets the newer surface
unconditionally, so the Switch build fails in two places:

  libs/JSystem/include/JSystem/JKernel/JKRAramPiece.h
      #include <dolphin/arq.h> - the separate ARQ header only exists in newer
      aurora. aurora-switch folds the same declarations (ARQRequest,
      ARQPostRequest, ARQCallback, ARQ_* constants) into <dolphin/ar.h>, and
      lib/dolphin/AR.cpp already implements ARQPostRequest. A forwarding header
      restores the include without touching dusk source.

  libs/JSystem/src/JFramework/JFWDisplay.cpp, JUtility/JUTVideo.cpp,
  src/dusk/speedrun.h, src/dusk/ui/overlay.cpp
      Call OSGetNativeTime() (declared in newer aurora's dolphin/os.h). On
      Switch, alias it to OSGetTime(): aurora-switch's OSGetTime already reports
      wall-clock time in GCN ticks since 2000-01-01, which is exactly what
      OSGetNativeTime returns on desktop. Same epoch, same tick rate, so RTA
      timing and frame pacing keep their meaning.

  libs/JSystem/src/JKernel/JKRArchivePri.cpp
      Calls DVDConvertEntrynumToPath(), which aurora-switch neither declares nor
      implements (newer aurora added it alongside overlay support). Rebuilt here
      on aurora-switch's own FST primitives rather than stubbed, so arc overlays
      keep resolving real paths on Switch.

Applied as a post-checkout patch rather than a fork: it keeps the aurora-switch
gitlink pinned and is idempotent, so a cache-restored tree is patched once.
"""

from __future__ import annotations

import sys
from pathlib import Path

ARQ_SHIM = """// Generated by ci/patches/aurora_switch_os_compat.py - do not edit.
//
// Newer aurora splits the ARQ declarations out of <dolphin/ar.h> into this
// header. aurora-switch predates the split and keeps them in ar.h, so forward.
#pragma once

#include <dolphin/ar.h>
"""

DECLARATION = "OSTime OSGetNativeTime(void);"

DVD_DECLARATION = "BOOL DVDConvertEntrynumToPath(s32 entrynum, char* path, u32 maxlen);"

# Rebuilt on aurora-switch's own primitives: s_entryNumToFstIndex maps a public
# entrynum to an FST index, and FSTEntry carries name/parent/isDir. Walks parents
# to the root and joins with '/', trailing slash for directories - the shape the
# desktop implementation returns.
DVD_IMPL = """BOOL DVDConvertEntrynumToPath(s32 entrynum, char* path, u32 maxlen) {
  std::lock_guard lock(s_fstLock);

  if (path == nullptr || maxlen == 0) {
    return FALSE;
  }
  path[0] = '\\0';

  if (!s_initialized || !isValidEntryNum(entrynum)) {
    return FALSE;
  }

  const FstIndex fstIndex = s_entryNumToFstIndex[entrynum];
  if (!isValidFstIndex(fstIndex)) {
    return FALSE;
  }

  std::vector<std::string> parts;
  for (FstIndex cur = fstIndex; cur > 0 && isValidFstIndex(cur);) {
    parts.push_back(s_fstEntries[cur].name);
    const FstIndex parent = s_fstEntries[cur].parent;
    if (parent == cur) {
      break;
    }
    cur = parent;
  }

  std::string entryPath;
  for (auto it = parts.rbegin(); it != parts.rend(); ++it) {
    entryPath += '/';
    entryPath += *it;
  }
  if (s_fstEntries[fstIndex].isDir && entryPath.size() > 1) {
    entryPath += '/';
  }
  if (entryPath.empty()) {
    entryPath = "/";
  }

  const size_t copyLen = std::min(entryPath.size(), static_cast<size_t>(maxlen - 1));
  std::memcpy(path, entryPath.data(), copyLen);
  path[copyLen] = '\\0';
  return entryPath.size() < maxlen ? TRUE : FALSE;
}

"""

DEFINITION = """
// Generated by ci/patches/aurora_switch_os_compat.py - do not edit.
// aurora-switch predates OSGetNativeTime(). OSGetTime() already returns
// wall-clock time in GCN ticks since 2000-01-01, which is what the desktop
// implementation returns via aurora::time::native_clock.
OSTime OSGetNativeTime(void) {
    return OSGetTime();
}
"""


def patch_arq_header(root: Path) -> str:
    shim = root / "include/dolphin/arq.h"
    if shim.exists():
        return "arq.h: already present"
    shim.write_text(ARQ_SHIM, encoding="utf-8", newline="\n")
    return "arq.h: created"


def patch_os_header(root: Path) -> str:
    header = root / "include/dolphin/os.h"
    text = header.read_text(encoding="utf-8")
    if DECLARATION in text:
        return "os.h: already declares OSGetNativeTime"
    anchor = "OSTime OSGetTime(void);"
    if anchor not in text:
        raise SystemExit(f"FATAL: cannot find '{anchor}' in {header}")
    text = text.replace(anchor, f"{anchor}\n{DECLARATION}", 1)
    header.write_text(text, encoding="utf-8", newline="")
    return "os.h: declaration added"


def patch_os_impl(root: Path) -> str:
    source = root / "lib/dolphin/os/OSTime.cpp"
    text = source.read_text(encoding="utf-8")
    if "OSGetNativeTime" in text:
        return "OSTime.cpp: already defines OSGetNativeTime"
    if not text.endswith("\n"):
        text += "\n"
    source.write_text(text + DEFINITION, encoding="utf-8", newline="")
    return "OSTime.cpp: definition appended"


GX_DECLARATION = "void AuroraGXSync(void);"

# Same body as desktop aurora: flush pending GX commands, then drain the FIFO.
# aurora-switch keeps both primitives (GXManage.cpp, aurora::gx::fifo::drain),
# it just never exported the combined helper.
GX_IMPL = """void AuroraGXSync() {
  GXFlush();
  aurora::gx::fifo::drain();
}

"""


def patch_gx_header(root: Path) -> str:
    header = root / "include/dolphin/gx/GXAurora.h"
    text = header.read_text(encoding="utf-8")
    if GX_DECLARATION in text:
        return "GXAurora.h: already declares AuroraGXSync"
    anchor = "void GXRestoreFrameBuffer(void);"
    if anchor not in text:
        raise SystemExit(f"FATAL: cannot find '{anchor}' in {header}")
    text = text.replace(anchor, f"{anchor}\n{GX_DECLARATION}", 1)
    header.write_text(text, encoding="utf-8", newline="")
    return "GXAurora.h: declaration added"


def patch_gx_impl(root: Path) -> str:
    source = root / "lib/dolphin/gx/GXAurora.cpp"
    text = source.read_text(encoding="utf-8")
    if "AuroraGXSync" in text:
        return "GXAurora.cpp: already defines AuroraGXSync"
    include = '#include "dolphin/gx/GXManage.h"'
    if include not in text:
        anchor = '#include "dolphin/gx/GXAurora.h"'
        if anchor not in text:
            raise SystemExit(f"FATAL: cannot find '{anchor}' in {source}")
        text = text.replace(anchor, f"{anchor}\n{include}", 1)
    anchor = "void GXCreateFrameBuffer(u32 width, u32 height) {"
    if anchor not in text:
        raise SystemExit(f"FATAL: cannot find '{anchor}' in {source}")
    text = text.replace(anchor, GX_IMPL + anchor, 1)
    source.write_text(text, encoding="utf-8", newline="")
    return "GXAurora.cpp: definition inserted"


def patch_dvd_header(root: Path) -> str:
    header = root / "include/dolphin/dvd.h"
    text = header.read_text(encoding="utf-8")
    if DVD_DECLARATION in text:
        return "dvd.h: already declares DVDConvertEntrynumToPath"
    anchor = "s32 DVDConvertPathToEntrynum(const char* pathPtr);"
    if anchor not in text:
        raise SystemExit(f"FATAL: cannot find '{anchor}' in {header}")
    text = text.replace(anchor, f"{anchor}\n{DVD_DECLARATION}", 1)
    header.write_text(text, encoding="utf-8", newline="")
    return "dvd.h: declaration added"


def patch_dvd_impl(root: Path) -> str:
    source = root / "lib/dolphin/dvd/dvd.cpp"
    text = source.read_text(encoding="utf-8")
    if "DVDConvertEntrynumToPath" in text:
        return "dvd.cpp: already defines DVDConvertEntrynumToPath"
    anchor = "BOOL DVDFastOpen(s32 entrynum, DVDFileInfo* fileInfo) {"
    if anchor not in text:
        raise SystemExit(f"FATAL: cannot find '{anchor}' in {source}")
    text = text.replace(anchor, DVD_IMPL + anchor, 1)
    source.write_text(text, encoding="utf-8", newline="")
    return "dvd.cpp: definition inserted"


def main() -> int:
    if len(sys.argv) != 2:
        print(f"usage: {sys.argv[0]} <path-to-aurora-switch>", file=sys.stderr)
        return 2

    root = Path(sys.argv[1]).resolve()
    if not (root / "include/dolphin/os.h").is_file():
        print(f"FATAL: {root} does not look like an aurora-switch checkout", file=sys.stderr)
        return 1

    for step in (
        patch_arq_header,
        patch_os_header,
        patch_os_impl,
        patch_gx_header,
        patch_gx_impl,
        patch_dvd_header,
        patch_dvd_impl,
    ):
        print(f"{root.name}: {step(root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
